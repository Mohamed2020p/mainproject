# helpers
# ---------------------------------------------------------------------------
def _is_value_type(type_def: Dict[str, Any]) -> bool:
    return (type_def["bitfield"] & 0x1) == 1


def _is_enum(type_def: Dict[str, Any]) -> bool:
    return ((type_def["bitfield"] >> 1) & 0x1) == 1


def _is_serializable(type_def: Dict[str, Any]) -> bool:
    return bool(type_def["flags"] & consts.TYPE_ATTRIBUTE_SERIALIZABLE)


def _type_visibility(type_def: Dict[str, Any]) -> str:
    visibility = type_def["flags"] & consts.TYPE_ATTRIBUTE_VISIBILITY_MASK
    return {
        consts.TYPE_ATTRIBUTE_PUBLIC: "public ",
        consts.TYPE_ATTRIBUTE_NESTED_PUBLIC: "public ",
        consts.TYPE_ATTRIBUTE_NOT_PUBLIC: "internal ",
        consts.TYPE_ATTRIBUTE_NESTED_FAM_AND_ASSEM: "internal ",
        consts.TYPE_ATTRIBUTE_NESTED_ASSEMBLY: "internal ",
        consts.TYPE_ATTRIBUTE_NESTED_PRIVATE: "private ",
        consts.TYPE_ATTRIBUTE_NESTED_FAMILY: "protected ",
        consts.TYPE_ATTRIBUTE_NESTED_FAM_OR_ASSEM: "protected internal ",
    }.get(visibility, "")


def _type_kind(type_def: Dict[str, Any]) -> str:
    flags = type_def["flags"]
    if flags & consts.TYPE_ATTRIBUTE_ABSTRACT and flags & consts.TYPE_ATTRIBUTE_SEALED:
        prefix = "static "
    elif not (flags & consts.TYPE_ATTRIBUTE_INTERFACE) and flags & consts.TYPE_ATTRIBUTE_ABSTRACT:
        prefix = "abstract "
    elif (not _is_value_type(type_def) and not _is_enum(type_def)
          and flags & consts.TYPE_ATTRIBUTE_SEALED):
        prefix = "sealed "
    else:
        prefix = ""
    if flags & consts.TYPE_ATTRIBUTE_INTERFACE:
        return prefix + "interface "
    if _is_enum(type_def):
        return prefix + "enum "
    if _is_value_type(type_def):
        return prefix + "struct "
    return prefix + "class "


def _field_access(attrs: int) -> str:
    return {
        consts.FIELD_ATTRIBUTE_PRIVATE: "private ",
        consts.FIELD_ATTRIBUTE_PUBLIC: "public ",
        consts.FIELD_ATTRIBUTE_FAMILY: "protected ",
        consts.FIELD_ATTRIBUTE_ASSEMBLY: "internal ",
        consts.FIELD_ATTRIBUTE_FAM_AND_ASSEM: "internal ",
        consts.FIELD_ATTRIBUTE_FAM_OR_ASSEM: "protected internal ",
    }.get(attrs & consts.FIELD_ATTRIBUTE_FIELD_ACCESS_MASK, "")


def _method_modifiers(method_def: Dict[str, Any], cache: Dict[int, str]) -> str:
    key = id(method_def)
    if key in cache:
        return cache[key]
    flags = method_def["flags"]
    text = {
        consts.METHOD_ATTRIBUTE_PRIVATE: "private ",
        consts.METHOD_ATTRIBUTE_PUBLIC: "public ",
        consts.METHOD_ATTRIBUTE_FAMILY: "protected ",
        consts.METHOD_ATTRIBUTE_ASSEM: "internal ",
        consts.METHOD_ATTRIBUTE_FAM_AND_ASSEM: "internal ",
        consts.METHOD_ATTRIBUTE_FAM_OR_ASSEM: "protected internal ",
    }.get(flags & consts.METHOD_ATTRIBUTE_MEMBER_ACCESS_MASK, "")

    if flags & consts.METHOD_ATTRIBUTE_STATIC:
        text += "static "
    if flags & consts.METHOD_ATTRIBUTE_ABSTRACT:
        text += "abstract "
        if (flags & consts.METHOD_ATTRIBUTE_VTABLE_LAYOUT_MASK) == consts.METHOD_ATTRIBUTE_REUSE_SLOT:
            text += "override "
    elif flags & consts.METHOD_ATTRIBUTE_FINAL:
        if (flags & consts.METHOD_ATTRIBUTE_VTABLE_LAYOUT_MASK) == consts.METHOD_ATTRIBUTE_REUSE_SLOT:
            text += "sealed override "
    elif flags & consts.METHOD_ATTRIBUTE_VIRTUAL:
        if (flags & consts.METHOD_ATTRIBUTE_VTABLE_LAYOUT_MASK) == consts.METHOD_ATTRIBUTE_NEW_SLOT:
            text += "virtual "
        else:
            text += "override "
    if flags & consts.METHOD_ATTRIBUTE_PINVOKE_IMPL:
        text += "extern "
    cache[key] = text
    return text


def escape_string(value: str) -> str:
    out = []
    for char in value:
        if char == "'":
            out.append("\\'")
        elif char == '"':
            out.append('\\"')
        elif char == "\\":
            out.append("\\\\")
        elif char == "\0":
            out.append("\\0")
        elif char == "\a":
            out.append("\\a")
        elif char == "\b":
            out.append("\\b")
        elif char == "\f":
            out.append("\\f")
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif char == "\v":
            out.append("\\v")
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append("\\x%02x" % ord(char))
        else:
            out.append(char)
    return "".join(out)


def format_constant(ok: bool, value: Any) -> str:
    if not ok:
        return "/*Metadata offset 0x%X*/" % (value if isinstance(value, int) else 0)
    if isinstance(value, str):
        return '"%s"' % escape_string(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return repr(value)
    if value is None:
        return "null"
    return str(value)
